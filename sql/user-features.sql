-- Run once after schema.sql. Adds user-owned places, profiles, group sharing,
-- and a shared purchase wishlist with one vote per user and game.
begin;

-- Places are private to each account.
create table if not exists public.places (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data jsonb not null
);
alter table public.places enable row level security;
drop policy if exists "Users manage their own places" on public.places;
create policy "Users manage their own places" on public.places
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create index if not exists places_user_id_idx on public.places(user_id);
create unique index if not exists places_user_name_unique_idx
  on public.places (user_id, lower(btrim(data->>'name')))
  where nullif(btrim(data->>'name'), '') is not null;

-- Reusable personal contacts. Groups store friend IDs, so a contact can belong to many lists.
create table if not exists public.friends (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data jsonb not null
);
alter table public.friends enable row level security;
drop policy if exists "Users manage their own friends" on public.friends;
create policy "Users manage their own friends" on public.friends
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create index if not exists friends_user_id_idx on public.friends(user_id);

-- Give each existing app group a stable key for sharing and safe upserts.
alter table public.groups add column if not exists app_id text;
update public.groups
set app_id = coalesce(nullif(data->>'id',''), 'legacy-' || id::text)
where app_id is null;
alter table public.groups alter column app_id set not null;
create unique index if not exists groups_user_app_id_unique_idx on public.groups(user_id, app_id);

create table if not exists public.group_shares (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  group_key text not null,
  member_email text not null,
  created_at timestamptz not null default now(),
  unique(owner_id, group_key, member_email)
);
alter table public.group_shares enable row level security;
drop policy if exists "Users see their group shares" on public.group_shares;
create policy "Users see their group shares" on public.group_shares
  for select to authenticated
  using (owner_id = auth.uid() or lower(member_email) = lower(auth.jwt()->>'email'));
drop policy if exists "Group owners invite members" on public.group_shares;
create policy "Group owners invite members" on public.group_shares
  for insert to authenticated with check (
    owner_id = auth.uid()
    and exists (select 1 from public.groups g where g.user_id = auth.uid() and g.app_id = group_key)
  );
drop policy if exists "Group owners revoke invitations" on public.group_shares;
create policy "Group owners revoke invitations" on public.group_shares
  for delete to authenticated using (owner_id = auth.uid());
create index if not exists group_shares_email_idx on public.group_shares(lower(member_email));

-- Owners and explicitly invited accounts can read and edit shared groups.
drop policy if exists "Users manage their own groups" on public.groups;
drop policy if exists "Groups readable by owner or invitee" on public.groups;
drop policy if exists "Groups insertable by owner or invitee" on public.groups;
drop policy if exists "Groups updateable by owner or invitee" on public.groups;
drop policy if exists "Groups deletable by owner" on public.groups;
create policy "Groups readable by owner or invitee" on public.groups
  for select to authenticated using (
    user_id = auth.uid() or exists (
      select 1 from public.group_shares s
      where s.owner_id = public.groups.user_id and s.group_key = public.groups.app_id
        and lower(s.member_email) = lower(auth.jwt()->>'email')
    )
  );
create policy "Groups insertable by owner or invitee" on public.groups
  for insert to authenticated with check (
    user_id = auth.uid() or exists (
      select 1 from public.group_shares s
      where s.owner_id = public.groups.user_id and s.group_key = public.groups.app_id
        and lower(s.member_email) = lower(auth.jwt()->>'email')
    )
  );
create policy "Groups updateable by owner or invitee" on public.groups
  for update to authenticated using (
    user_id = auth.uid() or exists (
      select 1 from public.group_shares s
      where s.owner_id = public.groups.user_id and s.group_key = public.groups.app_id
        and lower(s.member_email) = lower(auth.jwt()->>'email')
    )
  ) with check (
    user_id = auth.uid() or exists (
      select 1 from public.group_shares s
      where s.owner_id = public.groups.user_id and s.group_key = public.groups.app_id
        and lower(s.member_email) = lower(auth.jwt()->>'email')
    )
  );
create policy "Groups deletable by owner" on public.groups
  for delete to authenticated using (user_id = auth.uid());

-- Public-to-authenticated nickname directory; only the owner can change a nickname.
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null,
  created_at timestamptz not null default now(),
  constraint profiles_nickname_format check (nickname ~ '^[A-Za-z0-9_.-]{3,24}$')
);
insert into public.profiles(user_id, nickname)
select id,
  left(coalesce(nullif(regexp_replace(lower(split_part(coalesce(email,''),'@',1)), '[^a-z0-9_.-]', '', 'g'), ''), 'usuario'), 17)
  || '_' || left(replace(id::text, '-', ''), 6)
from auth.users
on conflict (user_id) do nothing;
create unique index if not exists profiles_nickname_unique_idx on public.profiles(lower(btrim(nickname)));
alter table public.profiles enable row level security;
drop policy if exists "Signed-in users can view nicknames" on public.profiles;
create policy "Signed-in users can view nicknames" on public.profiles
  for select to authenticated using (true);
drop policy if exists "Users create their own profile" on public.profiles;
create policy "Users create their own profile" on public.profiles
  for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Users update their own profile" on public.profiles;
create policy "Users update their own profile" on public.profiles
  for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create or replace function public.create_profile_for_new_auth_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare requested_nickname text;
begin
  requested_nickname := btrim(new.raw_user_meta_data->>'nickname');
  if requested_nickname is null or requested_nickname !~ '^[A-Za-z0-9_.-]{3,24}$' then
    raise exception 'Choose a nickname with 3–24 letters, numbers, dots, dashes or underscores';
  end if;
  insert into public.profiles(user_id, nickname) values (new.id, requested_nickname);
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users
  for each row execute procedure public.create_profile_for_new_auth_user();

-- Shared wishlist. Every authenticated user can propose and vote; only the
-- proposer can edit or remove their suggestion. A primary key prevents repeat votes.
create table if not exists public.wishlist_games (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (length(btrim(title)) between 1 and 120),
  url text not null,
  description text not null default '',
  price numeric(10,2) check (price is null or price >= 0),
  publisher text,
  players text,
  duration text,
  notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.wishlist_votes (
  game_id uuid not null references public.wishlist_games(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (game_id, user_id)
);
alter table public.wishlist_games enable row level security;
alter table public.wishlist_votes enable row level security;
drop policy if exists "Signed-in users view wishlist games" on public.wishlist_games;
create policy "Signed-in users view wishlist games" on public.wishlist_games
  for select to authenticated using (true);
drop policy if exists "Users propose wishlist games" on public.wishlist_games;
create policy "Users propose wishlist games" on public.wishlist_games
  for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Authors update their wishlist games" on public.wishlist_games;
create policy "Authors update their wishlist games" on public.wishlist_games
  for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "Authors delete their wishlist games" on public.wishlist_games;
create policy "Authors delete their wishlist games" on public.wishlist_games
  for delete to authenticated using (user_id = auth.uid());
drop policy if exists "Signed-in users view wishlist votes" on public.wishlist_votes;
create policy "Signed-in users view wishlist votes" on public.wishlist_votes
  for select to authenticated using (true);
drop policy if exists "Users cast their own votes" on public.wishlist_votes;
create policy "Users cast their own votes" on public.wishlist_votes
  for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Users retract their own votes" on public.wishlist_votes;
create policy "Users retract their own votes" on public.wishlist_votes
  for delete to authenticated using (user_id = auth.uid());

grant select, insert, update, delete on public.places, public.group_shares, public.profiles,
  public.wishlist_games, public.wishlist_votes, public.friends to authenticated;
grant select, insert, update, delete on public.groups to authenticated;

commit;
